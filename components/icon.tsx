export function vibeIcon(vibe: string): string {
  if (vibe === "Pool") return "home";
  if (vibe === "Bonfire") return "flame";
  if (vibe === "Countryside") return "leaf";
  if (vibe === "Pet friendly") return "paw";
  if (vibe === "Groups" || vibe === "Family") return "users";
  return "heart";
}
